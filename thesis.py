def overlap_count(query_terms: List[str], field_text: str) -> int:
    field_terms = set(tokenize(field_text))
    return sum(1 for t in query_terms if t in field_terms)


def confidence_boost(confidence: str) -> float:
    c = str(confidence).lower().strip()
    if c == "high":
        return 0.15
    if c == "medium":
        return 0.05
    return 0.0


def rerank_scores(
    df: pd.DataFrame,
    query: str,
    bm25_scores: List[float],
    vector_scores: List[float] | None = None,
    bm25_weight: float = 0.6,
    vector_weight: float = 0.4,
) -> List[float]:
    q_terms = tokenize(query)
    final_scores = []

    max_bm25 = max(bm25_scores) if bm25_scores and max(bm25_scores) > 0 else 1.0

    if vector_scores is None:
        vector_scores = [0.0] * len(bm25_scores)
        vector_weight = 0.0
        bm25_weight = 1.0

    max_vec = max(vector_scores) if vector_scores and max(vector_scores) > 0 else 1.0

    for idx, row in df.iterrows():
        bm25_norm = bm25_scores[idx] / max_bm25
        vec_norm = vector_scores[idx] / max_vec if max_vec > 0 else 0.0

        hybrid_base = bm25_weight * bm25_norm + vector_weight * vec_norm

        name = row.get("Equipment name", "")
        tags = row.get("Tags (5-10 keywords)", "")
        aliases = row.get("Aliases / synonyms", "")
        inputs = row.get("Inputs", "")
        outputs = row.get("Outputs", "")
        confidence = row.get("Confidence", "")

        exact_name = 0.0
        norm_name = normalize_text(name)
        norm_query = normalize_text(query)

        if norm_query in norm_name or norm_name in norm_query:
            exact_name += 0.35

        tag_boost = 0.04 * overlap_count(q_terms, tags)
        alias_boost = 0.03 * overlap_count(q_terms, aliases)
        io_boost = 0.03 * overlap_count(q_terms, inputs) + 0.03 * overlap_count(q_terms, outputs)
        conf_boost = confidence_boost(confidence)

        final = hybrid_base + exact_name + tag_boost + alias_boost + io_boost + conf_boost
        final_scores.append(final)

    return final_scores

"""Hybrid recommender"""

class HybridEquipmentRecommender:
    def __init__(self, df: pd.DataFrame, embedding_model: str = "all-MiniLM-L6-v2"):
        self.df = df.copy()
        self.df["search_text"] = self.df.apply(weighted_concat, axis=1)

        docs = self.df["search_text"].tolist()

        self.bm25 = BM25Retriever(docs)
        self.vector = FaissVectorRetriever(docs, model_name=embedding_model)

    def search(self, query: str, top_k: int = 10) -> pd.DataFrame:
        bm25_scores = self.bm25.score(query)
        vector_scores = self.vector.score(query)

        final_scores = rerank_scores(
            self.df,
            query,
            bm25_scores,
            vector_scores,
            bm25_weight=0.6,
            vector_weight=0.4,
        )

        out = self.df.copy()
        out["bm25_score"] = bm25_scores
        out["vector_score"] = vector_scores
        out["final_score"] = final_scores

        out = out.sort_values(["final_score", "bm25_score", "vector_score"], ascending=False).head(top_k)
        return out[
            [
                "Equipment name",
                "Aliases / synonyms",
                "Short description (2-3 sentences)",
                "Tags (5-10 keywords)",
                "Inputs",
                "Outputs",
                "University",
                "Confidence",
                "bm25_score",
                "vector_score",
                "final_score",
            ]
        ]

